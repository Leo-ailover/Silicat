FENCE_OPEN = re.compile(r"^```(\S*)\s*$")


def sha(s: str) -> str:
    return hashlib.sha1(s.encode("utf-8")).hexdigest()


def norm_key(s: str) -> str:
    return re.sub(r"\W+", " ", s.lower()).strip()   # punctuation-insensitive: "Pre-commit hook?" == "pre commit hook"


# ---- text helpers ---------------------------------------------------------

def fence_lines(text: str) -> int:
    return sum(1 for l in text.split("\n") if l.strip().startswith("```"))


def split_fences(text: str) -> list[tuple[str, str, str]]:
    """-> [(kind, lang, body)] with kind in {'text','code'}. Assumes balanced fences."""
    out, buf, lang, in_code = [], [], "", False
    for l in text.split("\n"):
        s = l.strip()
        if not in_code and s.startswith("```"):
            if buf:
                out.append(("text", "", "\n".join(buf)))
            buf, lang, in_code = [], s[3:].strip(), True
        elif in_code and s == "```":
            out.append(("code", lang, "\n".join(buf)))
            buf, in_code = [], False
        else:
            buf.append(l)
    if buf:
        out.append(("text" if not in_code else "code", lang, "\n".join(buf)))
    return out


def join_fences(parts: list[tuple[str, str, str]]) -> str:
    segs = []
    for kind, lang, body in parts:
        segs.append(f"```{lang}\n{body}\n```" if kind == "code" else body)
    return "\n".join(segs)


def parses(code: str) -> bool:
    try:
        ast.parse(code)
        return True
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        return False


def bound_names(tree: ast.AST) -> set[str]:
    b = set(dir(builtins))
    for n in ast.walk(tree):
        if isinstance(n, ast.Name) and isinstance(n.ctx, (ast.Store, ast.Del)):
            b.add(n.id)
        elif isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            b.add(n.name)
        elif isinstance(n, ast.arg):
            b.add(n.arg)
        elif isinstance(n, (ast.Import, ast.ImportFrom)):
            for a in n.names:
                b.add((a.asname or a.name).split(".")[0])
        elif isinstance(n, ast.ExceptHandler) and n.name:
            b.add(n.name)
    return b


def add_missing_imports(code: str) -> tuple[str, int]:
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return code, 0
    if "__future__" in code:
        return code, 0
    b = bound_names(tree)
    used = {n.value.id for n in ast.walk(tree) if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name)}
    need = sorted(x for x in used if x in AUTO_IMPORTS and x not in b)
    if not need:
        return code, 0
    lines = code.split("\n")
    at = 0
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], "value", None), ast.Constant) and isinstance(tree.body[0].value.value, str):
        at = tree.body[0].end_lineno
    new = lines[:at] + [f"import {x}" for x in need] + lines[at:]
    fixed = "\n".join(new)
    return (fixed, len(need)) if parses(fixed) else (code, 0)


def try_fix_python(code: str) -> str | None:
    cands = [textwrap.dedent(code)]
    c = code
    for _ in range(2):
        c += ")"
        cands.append(c)
    cands.append(re.sub(r"def (\w+) (\w+)\(", lambda m: f"def {m.group(1)}{m.group(2)[0].upper()}{m.group(2)[1:]}(", code))
    for cand in cands:
        if parses(cand):
            return cand
    return None


def is_fragment(code: str) -> bool:
    if re.match(r"\s*(except|else|elif|finally)\b", code) and (parses("try:\n    pass\n" + code) or parses("if x:\n    pass\n" + code)):
        return True
    return False


def normalise_message(text: str, st: Counter) -> str:
    text = text.replace("\r\n", "\n").strip()
    if fence_lines(text) % 2:
        return re.sub(r"\n{3,}", "\n\n", "\n".join(l.rstrip() for l in text.split("\n")))
    parts = []
    for kind, lang, body in split_fences(text):
        if kind == "text":
            body = "\n".join(l.rstrip() for l in body.split("\n"))
            body = re.sub(r"\n{3,}", "\n\n", body)
        parts.append((kind, lang, body))
    return join_fences(parts).strip()


# ---- row model ------------------------------------------------------------

class Row:
    __slots__ = ("source", "line", "msgs", "order", "ids_len", "trimmed", "derived_from", "replaces")

    def __init__(self, source: str, line: int, msgs: list[dict], order: int):
        self.source, self.line, self.msgs, self.order = source, line, msgs, order
        self.ids_len = 0
        self.trimmed = False
        self.derived_from = None
        self.replaces: list[str] = []

    @property
    def prompt(self) -> str:
        return self.msgs[0]["content"]

    @property
    def answer(self) -> str:
        return self.msgs[-1]["content"]

    def conv_hash(self) -> str:
        return sha("\x00".join(norm_key(m["content"]) if m["role"] == "user" else re.sub(r"\s+", " ", m["content"]).strip() for m in self.msgs))


def load_sources(st_drop: dict[str, Counter], read: Counter, log: list[str]) -> list[Row]:
    files = [BASE] + sorted(SYNTH_DIR.glob("*.jsonl"))
    rows, order = [], 0
    for f in files:
        src = f.stem
        with f.open(encoding="utf-8") as fh:
            for i, line in enumerate(fh, 1):
                if not line.strip():
                    continue
                read[src] += 1
                try:
                    obj = json.loads(line)
                except json.JSONDecodeError:
                    st_drop[src]["malformed_json"] += 1
                    log.append(f"{f.name}:{i}: malformed json: {line.strip()[:60]!r}")
                    continue
                msgs = obj.get("messages") if isinstance(obj, dict) else None
                reason = check_schema(msgs)
                if reason:
                    st_drop[src][reason] += 1
                    log.append(f"{f.name}:{i}: {reason}")
                    continue
                row = Row(src, i, [{"role": m["role"], "content": m["content"]} for m in msgs], order)
                row.derived_from = obj.get("derived_from")
                rep = obj.get("replaces")
                row.replaces = [rep] if isinstance(rep, str) else list(rep or [])
                rows.append(row)
                order += 1
    return rows


def check_schema(msgs) -> str | None:
    if not isinstance(msgs, list) or len(msgs) < 2 or len(msgs) % 2:
        return "role_order" if isinstance(msgs, list) and msgs else "bad_schema"
    for i, m in enumerate(msgs):
        if not isinstance(m, dict) or set(m) - {"role", "content"} or not isinstance(m.get("content"), str):
            return "bad_schema"
        if m.get("role") != ("user" if i % 2 == 0 else "silicat"):
            return "role_order" if m.get("role") in ("user", "silicat") else "bad_schema"
        if not m["content"].strip():
            return "empty_message"
    return None


# ---- filters --------------------------------------------------------------

def python_pass(row: Row, st: Counter) -> str | None:
    """Fix/relabel python blocks in place; return drop reason or None."""
    deliberate = bool(DELIBERATE_RE.search(" ".join(m["content"] for m in row.msgs)))
    for m in row.msgs:
        if m["role"] != "silicat":
            continue
        parts = split_fences(m["content"])
        for i, (kind, lang, body) in enumerate(parts):
            if kind != "code":
                continue
            if lang == "":
                lang = "python" if parses(body) and not NON_PY_RE.search(body) else "text"
                if lang == "text" and not parses(body):
                    pass
                st["fence_tagged_" + lang] += 1
            elif lang.lower() in ("py", "python3"):
                lang = "python"
            if lang == "python":
                if parses(body):
                    if not deliberate:
                        body2, n = add_missing_imports(body)
                        if n:
                            st["imports_added"] += 1
                            body = body2
                elif is_fragment(body) or deliberate:
                    st["python_fragment_kept"] += 1
                else:
                    fixed = try_fix_python(body)
                    if fixed is not None:
                        body = fixed
                        st["python_trivially_fixed"] += 1
                    elif NON_PY_RE.search(body):
                        lang = "text"
                        st["python_relabelled_text"] += 1
                    else:
                        return "syntax_error"
            parts[i] = (kind, lang, body)
        m["content"] = join_fences(parts)
    return None


def junk_reason(row: Row, template_keys: set[tuple[str, str]]) -> str | None:
    a = row.answer
    if any(r.match(row.prompt.strip()) for r in JUNK_RES):
        return "template_junk"
    if len(row.msgs) == 2 and (re.sub(r"\d+", "#", row.prompt), re.sub(r"\d+", "#", a)) in template_keys:
        return "template_junk"
    if any(m["role"] == "silicat" and IDENTITY_BAD_RE.search(m["content"]) for m in row.msgs):
        return "identity_conflict"
    code = [b for k, _, b in split_fences(a) if k == "code"]
    prose = " ".join(b for k, _, b in split_fences(a) if k == "text").strip()
    if code and all(all(not l.strip() or l.strip().startswith("#") or l.strip() in ("pass", "...") for l in c.split("\n")) for c in code) and len(prose) < 80:
        return "placeholder_answer"
    return None


def telegraphic(row: Row) -> bool:
    if row.source in ("silicat_chat", "identity", "paste_code") or len(row.msgs) != 2:
        return False
    a, u = row.answer, row.prompt
    has_code = "```" in a
    if has_code:
        return False
    if len(a) <= 40 and len(u.split()) <= 4:
        return True
    if HOWTO_RE.match(u.strip()) and len(a) < 80:
        return True
    return len(a) <= 30 and len(u.split()) <= 6


# ---- near-duplicate clustering -------------------------------------------

def shingles(text: str, n: int = 3) -> set[int]:
    w = re.findall(r"\w+|[^\w\s]", text.lower())
    if len(w) < n:
        return {int(hashlib.md5(" ".join(w).encode()).hexdigest()[:8], 16)} if w else set()
    return {int(hashlib.md5(" ".join(w[i : i + n]).encode()).hexdigest()[:8], 16) for i in range(len(w) - n + 1)}


class MinHash:
    def __init__(self, perms: int = 64, bands: int = 16, seed: int = 0):
        rng = np.random.RandomState(seed)
        self.p = (1 << 61) - 1
        self.a = rng.randint(1, 1 << 30, size=perms).astype(object)
        self.b = rng.randint(0, 1 << 30, size=perms).astype(object)
        self.bands, self.rows = bands, perms // bands

    def sig(self, sh: set[int]) -> tuple[int, ...]:
        if not sh:
            return (0,) * (self.bands * self.rows)
        x = np.fromiter(sh, dtype=np.uint64)
        a = np.array(self.a, dtype=np.uint64)[:, None]
        b = np.array(self.b, dtype=np.uint64)[:, None]
        return tuple(((a * x[None, :] + b) % np.uint64(4294967291)).min(axis=1).tolist())

    def bucket_keys(self, sig):
        for i in range(self.bands):
            yield i, hash(sig[i * self.rows : (i + 1) * self.rows])


ANSWER_MIN_CHARS = 40   # shorter answers ("Yes.", one-liners) legitimately repeat across prompts
CODE_MIN_CHARS = 60


def answer_keys(r: "Row") -> tuple[set[str], set[int]]:
    """(exact keys, 5-gram shingles) of the final answer: its normalised text and each code block (long enough only)."""
    ans = r.answer
    keys = set()
    na = norm_key(ans)
    if len(na) >= ANSWER_MIN_CHARS:
        keys.add("a:" + na)
    for kind, _lang, body in split_fences(ans):
        if kind == "code":
            nb = re.sub(r"\s+", " ", body).strip()
            if len(nb) > CODE_MIN_CHARS:
                keys.add("c:" + nb)
    return keys, (shingles(ans, 5) if len(na) >= ANSWER_MIN_CHARS else set())


def jaccard(a: set[int], b: set[int]) -> float:
    return len(a & b) / len(a | b) if a and b else 0.0


class UF:
    def __init__(self, n: int):
        self.p = list(range(n))

    def find(self, x: int) -> int:
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def union(self, a: int, b: int) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[max(ra, rb)] = min(ra, rb)


def row_text(r: Row) -> str:
    return " \n ".join(m["content"] for m in r.msgs)


def survivor_key(r: Row):
    py_ok = all(parses(b) for m in r.msgs if m["role"] == "silicat" for k, l, b in split_fences(m["content"]) if k == "code" and l == "python")
    return (r.source == "identity", py_ok, len(r.answer), -r.order)


# ---- main -----------------------------------------------------------------

def parse_args(argv=None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="Build silicat_chat_v3.jsonl / silicat_chat_eval.jsonl / chat_stats.json")
    ap.add_argument("--block-size", type=int, default=512)
    ap.add_argument("--eval-size", type=int, default=300)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--tokenizer", type=Path, default=TOK_DIR)
    ap.add_argument("--no-length-filter", action="store_true", help="skip token-length filtering (e.g. no tokenizer available)")
    ap.add_argument("--out", type=Path, default=OUT_TRAIN)
    ap.add_argument("--eval-out", type=Path, default=OUT_EVAL)
    ap.add_argument("--stats", type=Path, default=OUT_STATS)
    return ap.parse_args(argv)


def main() -> None:
    build(parse_args())


def build(args: argparse.Namespace, exclude: frozenset[str] = frozenset(), write: bool = True):
    """Run the whole pipeline. `exclude` names sources (file stems) to ignore;
    gen_paste_code.py uses exclude={"paste_code"} to mine clean train-split code.
    Returns (train_rows, eval_rows)."""
    drops: dict[str, Counter] = defaultdict(Counter)
    read: Counter = Counter()
    log: list[str] = []
    notes: Counter = Counter()
    rows = [r for r in load_sources(drops, read, log) if r.source not in exclude]
    for x in exclude:
        read.pop(x, None)
    for l in log:
        print("  skip", l)

    # upgraded rows (data/synth/upgraded_*.jsonl, field "replaces" = original prompt) retire the originals
    replaced = {norm_key(p) for r in rows for p in r.replaces}
    drop_file = ROOT / "data" / "upgrade" / "drop_prompts.txt"
    if drop_file.exists():  # off-topic rows retired by hand review
        off = {norm_key(l) for l in drop_file.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")}
        rows = [r for r in rows if norm_key(r.prompt) not in off or drops[r.source].update(["off_topic"])]
    if replaced:
        rows = [r for r in rows if r.replaces or norm_key(r.prompt) not in replaced or drops[r.source].update(["upgraded"])]

    # normalise + literal fixes
    for r in rows:
        for m in r.msgs:
            m["content"] = normalise_message(m["content"], notes)
            if m["role"] == "silicat":
                for pat, rep in COMMENT_FIXES:
                    m["content"], n = re.subn(pat, rep, m["content"])
                    notes["comment_value_fixes"] += n
                for a, b in LITERAL_FIXES:
                    if a in m["content"]:
                        m["content"] = m["content"].replace(a, b)
                        notes["literal_api_fixes"] += 1

    def drop(r: Row, reason: str) -> None:
        drops[r.source][reason] += 1

    keep = []
    for r in rows:
        if any(m["role"] == "silicat" and fence_lines(m["content"]) % 2 for m in r.msgs):
            drop(r, "unterminated_fence")
        else:
            keep.append(r)
    rows = keep

    groups = Counter()
    for r in rows:
        if len(r.msgs) == 2:
            groups[(re.sub(r"\d+", "#", r.prompt), re.sub(r"\d+", "#", r.answer))] += 1
    template_keys = {k for k, n in groups.items() if n >= TEMPLATE_GROUP_MIN}
    keep = []
    for r in rows:
        why = junk_reason(r, template_keys)
        if why:
            drop(r, why)
        else:
            keep.append(r)
    rows = keep

    keep = []
    for r in rows:
        why = python_pass(r, notes)
        if why:
            drop(r, why)
        elif telegraphic(r):
            drop(r, "telegraphic")
        else:
            keep.append(r)
    rows = keep

    # token length
    if not args.no_length_filter:
        from silicat.chat_format import Message, format_for_training
        from silicat.tokenizer import Tokenizer

        tok = Tokenizer(args.tokenizer)

        def n_tok(msgs):
            return len(format_for_training([Message(m["role"], m["content"]) for m in msgs], tok)[0])

        keep = []
        for r in rows:
            n = n_tok(r.msgs)
            if n > args.block_size:
                k = len(r.msgs)
                while k > 2 and n > args.block_size:
                    k -= 2
                    n = n_tok(r.msgs[:k])
                if n > args.block_size:
                    drop(r, "too_long")
                    continue
                r.msgs = r.msgs[:k]
                r.trimmed = True
                notes["trimmed_multiturn"] += 1
            r.ids_len = n
            keep.append(r)
        rows = keep

    # exact duplicates
    seen, keep = {}, []
    for r in rows:
        h = r.conv_hash()
        if h in seen:
            drop(r, "exact_duplicate")
        else:
            seen[h] = r
            keep.append(r)
    rows = keep

    # clusters: same normalised first prompt, or MinHash Jaccard >= 0.8
    uf = UF(len(rows))
    by_prompt: dict[str, int] = {}
    mh = MinHash(seed=args.seed)
    shs = [shingles(row_text(r)) for r in rows]
    buckets: dict[tuple[int, int], list[int]] = defaultdict(list)
    for i, r in enumerate(rows):
        k = norm_key(r.prompt)
        if k in by_prompt:
            uf.union(i, by_prompt[k])
        else:
            by_prompt[k] = i
        if r.source in SYNTHETIC_SOURCES:  # paraphrases of one fact share answers on purpose
            continue
        for key in mh.bucket_keys(mh.sig(shs[i])):
            buckets[key].append(i)
    n_near = 0
    for idxs in buckets.values():
        for j in idxs[1:]:
            i = idxs[0]
            if uf.find(i) != uf.find(j) and jaccard(shs[i], shs[j]) >= 0.8:
                uf.union(i, j)
                n_near += 1
    clusters: dict[int, list[int]] = defaultdict(list)
    for i in range(len(rows)):
        clusters[uf.find(i)].append(i)
    survivors = []
    for members in clusters.values():
        best = max(members, key=lambda i: survivor_key(rows[i]))
        survivors.append(rows[best])
        for i in members:
            if i != best:
                same_prompt = norm_key(rows[i].prompt) == norm_key(rows[best].prompt)
                drop(rows[i], "same_prompt_duplicate" if same_prompt else "near_duplicate")
    survivors.sort(key=lambda r: r.order)

    # stratified eval split
    rng = random.Random(args.seed)
    pool: dict[str, list[Row]] = defaultdict(list)
    for r in survivors:
        if r.source not in SYNTHETIC_SOURCES:
            pool[r.source].append(r)
    total = sum(len(v) for v in pool.values())
    quota, rem = {}, []
    for s, v in pool.items():
        exact = args.eval_size * len(v) / total
        quota[s] = int(exact) if len(v) >= 20 else 0
        rem.append((exact - int(exact), s))
    left = args.eval_size - sum(quota.values())
    for _, s in sorted(rem, reverse=True):
        if left <= 0:
            break
        if len(pool[s]) >= 20:
            quota[s] += 1
            left -= 1
    # Answer-level leak guard: an eval row must not share its final answer (exact, any code block, or 5-gram
    # Jaccard >= 0.6) with ANY other survivor, otherwise train would contain it under a different prompt.
    akeys = [answer_keys(r) for r in survivors]
    pos = {id(r): i for i, r in enumerate(survivors)}
    key_idx: dict[str, list[int]] = defaultdict(list)
    sh_idx: dict[int, list[int]] = defaultdict(list)
    for i, (ks, sh) in enumerate(akeys):
        for k in ks:
            key_idx[k].append(i)
        for h in sh:
            sh_idx[h].append(i)

    def has_answer_twin(r: Row) -> bool:
        i = pos[id(r)]
        ks, sh = akeys[i]
        if any(len(key_idx[k]) > 1 for k in ks):
            return True
        shared: Counter = Counter()
        for h in sh:
            for j in sh_idx[h]:
                if j != i:
                    shared[j] += 1
        return any(c / (len(sh) + len(akeys[j][1]) - c) >= 0.6 for j, c in shared.items())

    eval_rows: list[Row] = []
    for s in sorted(pool):
        ranked = sorted(pool[s], key=lambda r: sha(f"{args.seed}:{norm_key(r.prompt)}"))
        eval_rows += [r for r in ranked if not has_answer_twin(r)][: quota[s]]
    eval_ids = {id(r) for r in eval_rows}
    eval_keys = {norm_key(r.prompt) for r in eval_rows}
    train_rows = []
    for r in survivors:
        if id(r) in eval_ids:
            continue
        if r.derived_from and r.derived_from in eval_keys:
            drop(r, "derived_from_eval")
            continue
        train_rows.append(r)
    rng.shuffle(train_rows)
    eval_rows.sort(key=lambda r: r.order)

    # disjointness checks
    tp = {norm_key(r.prompt) for r in train_rows}
    assert not any(norm_key(r.prompt) in tp for r in eval_rows), "eval/train prompt overlap"
    th = {r.conv_hash() for r in train_rows}
    assert not any(r.conv_hash() in th for r in eval_rows)
    train_keys = {k for r in train_rows for k in answer_keys(r)[0]}
    assert not any(answer_keys(r)[0] & train_keys for r in eval_rows), "eval/train answer or code-block overlap"

    def dump(path: Path, rs: list[Row]) -> None:
        tmp = path.with_suffix(path.suffix + ".tmp")
        with tmp.open("w", encoding="utf-8") as f:
            for r in rs:
                f.write(json.dumps({"messages": r.msgs}, ensure_ascii=False) + "\n")
        tmp.replace(path)

    if not write:
        return train_rows, eval_rows
    dump(args.out, train_rows)
    dump(args.eval_out, eval_rows)

    kept_train, kept_eval = Counter(r.source for r in train_rows), Counter(r.source for r in eval_rows)
    per_source = {}
    for s in sorted(read):
        per_source[s] = {
            "read": read[s], "kept_train": kept_train[s], "kept_eval": kept_eval[s],
            "dropped": dict(sorted(drops[s].items())),
        }
    by_reason = Counter()
    for c in drops.values():
        by_reason.update(c)
    lens = sorted(r.ids_len for r in train_rows) if not args.no_length_filter else []
    stats = {
        "args": {"block_size": args.block_size, "eval_size": args.eval_size, "seed": args.seed, "length_filter": not args.no_length_filter},
        "total": {"read": sum(read.values()), "kept_train": len(train_rows), "kept_eval": len(eval_rows), "dropped_by_reason": dict(sorted(by_reason.items()))},
        "fixes_applied": dict(sorted(notes.items())),
        "train_token_len": ({"mean": round(sum(lens) / len(lens), 1), "p50": lens[len(lens) // 2], "p95": lens[int(len(lens) * 0.95)], "max": lens[-1]} if lens else None),
        "train_multi_turn_rows": sum(1 for r in train_rows if len(r.msgs) > 2),
        "per_source": per_source,
        "skipped_lines": log,
    }
    args.stats.write_text(json.dumps(stats, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"read {sum(read.values())} -> train {len(train_rows)}, eval {len(eval_rows)}")
    for k, v in sorted(by_reason.items(), key=lambda x: -x[1]):
        print(f"  dropped {k:24s} {v}")
    for k, v in sorted(notes.items()):
        print(f"  fix     {k:24s} {v}")


if __name__ == "__main__":
    main()
