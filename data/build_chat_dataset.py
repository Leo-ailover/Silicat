"""Build the chat fine-tuning data deterministically from the committed sources.

Inputs (the committed JSONL files are the source of truth; the LLM generators
in data/synth/gen_*.py only cover 7 of the 35 synth files):
    data/silicat_chat.jsonl, sorted(data/synth/*.jsonl)
Outputs:
    data/silicat_chat_v3.jsonl    train   ({"messages":[{"role","content"},...]})
    data/silicat_chat_eval.jsonl  held-out (~300 rows, stratified by source)
    data/chat_stats.json          counts before/after per source and per reason

Never reads its own outputs, so re-running is idempotent. Pipeline order (every
dropped row is counted under one reason, per source):
  1. parse     malformed_json (log lines, truncated lines; logged with file:line)
  2. schema    bad_schema / empty_message / role_order (user,silicat,... strictly
               alternating, starts user, ends silicat, non-empty strings)
  3. normalise strip each message, rstrip lines and collapse 3+ newlines OUTSIDE
               code fences, tag unlabeled fences (python if it parses, else text),
               literal API fixes, add missing stdlib imports (ast-based, only when
               the name is used and never bound)
  4. junk      unterminated_fence (odd count of lines starting with ```),
               template_junk (digit-masked (prompt,answer) groups of >= 10 rows plus
               four explicit deny-list regexes), placeholder_answer,
               identity_conflict (old rows claiming 10M/200M params),
               telegraphic (synth only: keyword -> slogan, how-to without code)
  5. python    syntax_error: ```python blocks failing ast.parse. Kept when the row
               is about errors/bugs, the block is an except/else fragment, or a
               trivial fix works (dedent, close brackets, `def a B(` typo);
               non-Python content labelled python is relabelled text; anything
               else is dropped. Code is never executed.
  6. length    too_long: tokenised length (silicat.chat_format.format_for_training,
               checkpoints/tokenizer_v2) > --block-size. Multi-turn rows are
               trimmed to the longest prefix of complete turn pairs that fits
               (counted as trimmed_multiturn); never cut mid-answer, so <|end|>
               is always present.
  7. dedup     exact_duplicate (normalised conversation hash) then clusters
               (union-find) of rows with the same normalised first prompt or
               MinHash/Jaccard >= 0.8 on prompt+answers (near_duplicate). One
               survivor per cluster: identity source > answers whose python blocks
               all parse > longer final answer > earlier file order.
  8. split     ~--eval-size rows into the eval file, stratified by source
               (largest-remainder quotas), chosen by prompt hash. Whole clusters
               collapse to one row first, so train/eval share no normalised
               prompt and no >= 0.8 near-duplicate; asserted at the end.
Train is shuffled with --seed. Generated sources (identity, paste_code) stay in train.

Usage: python data/build_chat_dataset.py [--block-size 512] [--eval-size 300]
                                         [--seed 0] [--no-length-filter]
"""
